"""Data product governance as code: sensitivity label, tags and endorsement on each data product lakehouse,
as rendered by the domains stack (output `data_product_governance`).

    uv run data-product-governance           # dry run: show what differs from Terraform; exits 1 on drift
    uv run data-product-governance --apply   # set labels and tags; report endorsement still to do

* Labels: Admin API bulkSetLabels (Fabric administrator *user* only, 25 calls/hour). Fabric also labels the
  lakehouse's autogenerated SQL analytics endpoint. In GitHub Actions (service principal) labels are only checked:
  the tool exits non-zero while they differ, and a Fabric administrator re-runs it locally with --apply.
* Tags: applyTags / unapplyTags per item.
* Endorsement: Fabric has no API to promote or certify an item. The tool reads it back (scanner API) and exits
  non-zero while it differs, so the manual portal step in the README is still checked by code. A product whose
  endorsement is null in Terraform (dev) is not checked.
"""

from __future__ import annotations

import argparse
import time
from dataclasses import dataclass

from fabric_mesh_tools import terraform
from fabric_mesh_tools.api import FABRIC, POWERBI_SCOPE, request
from fabric_mesh_tools.fabric_auth import in_github_actions

SCANNER = "https://api.powerbi.com/v1.0/myorg/admin/workspaces"


@dataclass
class ProductDiff:
    label_ok: bool
    tags_add: set[str]
    tags_remove: set[str]
    endorsement: str  # current endorsement
    endorsement_ok: bool

    @property
    def tags_ok(self) -> bool:
        return not (self.tags_add or self.tags_remove)


def diff_product(product: dict, scanned: dict, current_tags: set[str]) -> ProductDiff:
    """Compare one product's Terraform governance with its scanner entry and live tags."""
    label = (scanned.get("sensitivityLabel") or {}).get("labelId")
    endorsement = (scanned.get("endorsementDetails") or {}).get("endorsement", "None")
    wanted_tags = set(product["tags"].values())
    return ProductDiff(
        label_ok=label == product["label_id"],
        tags_add=wanted_tags - current_tags,
        tags_remove=current_tags - wanted_tags,
        endorsement=endorsement,
        endorsement_ok=product.get("endorsement") is None or endorsement == product["endorsement"],
    )


def scan(workspace_ids: list[str]) -> dict[str, dict]:
    """Item ID => scanner entry (sensitivityLabel, endorsementDetails) for every item in the workspaces."""
    scan_id = request("POST", f"{SCANNER}/getInfo", {"workspaces": workspace_ids}, POWERBI_SCOPE)["id"]
    while request("GET", f"{SCANNER}/scanStatus/{scan_id}", scope=POWERBI_SCOPE)["status"] != "Succeeded":
        time.sleep(3)
    result = request("GET", f"{SCANNER}/scanResult/{scan_id}", scope=POWERBI_SCOPE)
    return {
        item["id"]: item
        for ws in result["workspaces"]
        for items in ws.values()
        if isinstance(items, list)
        for item in items
        if isinstance(item, dict) and "id" in item
    }


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--apply", action="store_true", help="set labels (user only) and tags that differ")
    args = parser.parse_args(argv)

    desired = terraform.output(terraform.DOMAINS_STACK, "data_product_governance")
    scanned = scan(sorted({p["workspace_id"] for p in desired.values()}))

    diffs: dict[str, ProductDiff] = {}
    for key, p in sorted(desired.items()):
        item = request("GET", f"{FABRIC}/workspaces/{p['workspace_id']}/items/{p['item_id']}")
        d = diffs[key] = diff_product(p, scanned.get(p["item_id"], {}), {t["id"] for t in item.get("tags", [])})
        wanted = p.get("endorsement") or "not checked"
        print(
            f"{key:<10} label {'ok    ' if d.label_ok else 'change'} {p['label']:<13}"
            f" tags {'ok    ' if d.tags_ok else 'change'} {', '.join(sorted(p['tags']))}"
            f"  endorsement {'ok    ' if d.endorsement_ok else 'MANUAL'} {wanted}"
        )

    relabel: dict[str, list[dict]] = {}  # label ID => items
    for key, d in diffs.items():
        if not d.label_ok:
            relabel.setdefault(desired[key]["label_id"], []).append(
                {"id": desired[key]["item_id"], "type": desired[key]["item_type"]}
            )
    retag = [k for k, d in diffs.items() if not d.tags_ok]
    endorse = [f"{k}: {d.endorsement} -> {desired[k]['endorsement']}" for k, d in diffs.items() if not d.endorsement_ok]

    if args.apply:
        for label_id, items in relabel.items() if not in_github_actions() else ():
            statuses = request("POST", f"{FABRIC}/admin/items/bulkSetLabels", {"items": items, "labelId": label_id})
            for s in statuses["itemsChangeLabelStatus"]:
                print(f"label   {s['id']} -> {s['status']}")
        for key in retag:
            p, d = desired[key], diffs[key]
            base = f"{FABRIC}/workspaces/{p['workspace_id']}/items/{p['item_id']}"
            if d.tags_add:
                request("POST", f"{base}/applyTags", {"tags": sorted(d.tags_add)})
            if d.tags_remove:
                request("POST", f"{base}/unapplyTags", {"tags": sorted(d.tags_remove)})
            print(f"tags    {key}: +{len(d.tags_add)} -{len(d.tags_remove)}")
    elif relabel or retag:
        print(f"\n{sum(map(len, relabel.values()))} label(s) and {len(retag)} tag set(s) differ. Re-run with --apply.")

    if not args.apply and (relabel or retag):
        raise SystemExit(
            "Labels or tags differ" + (" (and endorsement: " + "; ".join(endorse) + ")" if endorse else "") + "."
        )
    if args.apply and relabel and in_github_actions():
        raise SystemExit(
            "Labels differ and bulkSetLabels does not support service principals: run locally with --apply."
        )
    if endorse:
        print("\nEndorsement has no API: set it in the portal (item settings → Endorsement), then re-run.")
        raise SystemExit("Endorsement differs: " + "; ".join(endorse))
    if not (relabel or retag):
        print("Data product governance matches Terraform.")


if __name__ == "__main__":
    main()
