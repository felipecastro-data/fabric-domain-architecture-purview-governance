"""Data product governance as code: sensitivity label, tags and endorsement on each data product lakehouse,
as rendered by the domains stack (output `data_product_governance`).

python tools/data_product_governance.py           # dry run: show what differs from Terraform; exits 1 on drift
python tools/data_product_governance.py --apply   # set labels and tags; report endorsement still to do

* Labels: Admin API bulkSetLabels (Fabric administrator *user* only, 25 calls/hour). Fabric also labels the
  lakehouse's autogenerated SQL analytics endpoint. In GitHub Actions (service principal) labels are only checked:
  the tool exits non-zero while they differ, and a Fabric administrator re-runs it locally with --apply.
* Tags: applyTags / unapplyTags per item.
* Endorsement: Fabric has no API to promote or certify an item. The tool reads it back (scanner API) and exits
  non-zero while it differs, so the manual portal step in the README is still checked by code.
"""

from __future__ import annotations

import json
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

from fabric_auth import access_token, in_github_actions  # fresh GitHub OIDC exchange in CI, az CLI locally

API = "https://api.fabric.microsoft.com/v1"
SCANNER = "https://api.powerbi.com/v1.0/myorg/admin/workspaces"
POWERBI_SCOPE = "https://analysis.windows.net/powerbi/api/.default"
DOMAINS_STACK = Path(__file__).resolve().parents[1] / "infra" / "terraform" / "domains"


def req(method: str, url: str, body: dict | None = None, scope: str | None = None) -> dict | None:
    data = json.dumps(body).encode() if body is not None else None
    token = access_token(scope) if scope else access_token()
    headers = {"Authorization": f"Bearer {token}", "Content-Type": "application/json"}
    for attempt in range(3):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, data=data, method=method, headers=headers), timeout=60) as r:  # noqa: S310
                raw = r.read()
                return json.loads(raw) if raw else None
        except urllib.error.HTTPError as exc:
            raise SystemExit(f"{method} {url} -> {exc.code} {exc.read().decode()}") from exc
        except urllib.error.URLError:  # transient connection failures; HTTP errors are never retried
            if attempt == 2:
                raise
            time.sleep(5)
    return None


def desired_products() -> dict[str, dict]:
    out = subprocess.run(
        ["terraform", f"-chdir={DOMAINS_STACK}", "output", "-json", "data_product_governance"],
        check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def scan(workspace_ids: list[str]) -> dict[str, dict]:
    """Item ID => scanner entry (sensitivityLabel, endorsementDetails) for every item in the workspaces."""
    scan_id = req("POST", f"{SCANNER}/getInfo", {"workspaces": workspace_ids}, POWERBI_SCOPE)["id"]
    while req("GET", f"{SCANNER}/scanStatus/{scan_id}", scope=POWERBI_SCOPE)["status"] != "Succeeded":
        time.sleep(3)
    result = req("GET", f"{SCANNER}/scanResult/{scan_id}", scope=POWERBI_SCOPE)
    return {
        item["id"]: item
        for ws in result["workspaces"]
        for items in ws.values() if isinstance(items, list)
        for item in items if isinstance(item, dict) and "id" in item
    }


def main(apply: bool) -> None:
    desired = desired_products()
    scanned = scan(sorted({p["workspace_id"] for p in desired.values()}))

    relabel: dict[str, list[dict]] = {}  # label ID => items
    retag: dict[str, tuple[dict, set[str], set[str]]] = {}  # product => (product, tags to apply, tags to remove)
    endorse: list[str] = []
    for key, p in sorted(desired.items()):
        item = scanned.get(p["item_id"], {})
        label = (item.get("sensitivityLabel") or {}).get("labelId")
        endorsement = (item.get("endorsementDetails") or {}).get("endorsement", "None")
        current_tags = {
            t["id"] for t in req("GET", f"{API}/workspaces/{p['workspace_id']}/items/{p['item_id']}").get("tags", [])
        }
        wanted_tags = set(p["tags"].values())

        if label != p["label_id"]:
            relabel.setdefault(p["label_id"], []).append({"id": p["item_id"], "type": p["item_type"]})
        if current_tags != wanted_tags:
            retag[key] = (p, wanted_tags - current_tags, current_tags - wanted_tags)
        if endorsement != p["endorsement"]:
            endorse.append(f"{key}: {endorsement} -> {p['endorsement']}")

        print(
            f"{key:<10} label {'ok    ' if label == p['label_id'] else 'change'} {p['label']:<13}"
            f" tags {'ok    ' if key not in retag else 'change'} {', '.join(sorted(p['tags']))}"
            f"  endorsement {'ok    ' if endorsement == p['endorsement'] else 'MANUAL'} {p['endorsement']}"
        )

    if apply:
        for label_id, items in relabel.items() if not in_github_actions() else ():
            statuses = req("POST", f"{API}/admin/items/bulkSetLabels", {"items": items, "labelId": label_id})
            for s in statuses["itemsChangeLabelStatus"]:
                print(f"label   {s['id']} -> {s['status']}")
        for key, (p, add, remove) in retag.items():
            base = f"{API}/workspaces/{p['workspace_id']}/items/{p['item_id']}"
            if add:
                req("POST", f"{base}/applyTags", {"tags": sorted(add)})
            if remove:
                req("POST", f"{base}/unapplyTags", {"tags": sorted(remove)})
            print(f"tags    {key}: +{len(add)} -{len(remove)}")
    elif relabel or retag:
        print(f"\n{sum(map(len, relabel.values()))} label(s) and {len(retag)} tag set(s) differ. Re-run with --apply.")

    if not apply and (relabel or retag):
        raise SystemExit("Labels or tags differ" + (" (and endorsement: " + "; ".join(endorse) + ")" if endorse else "") + ".")
    if apply and relabel and in_github_actions():
        raise SystemExit("Labels differ and bulkSetLabels does not support service principals: run locally with --apply.")
    if endorse:
        print("\nEndorsement has no API: set it in the portal (item settings → Endorsement), then re-run.")
        raise SystemExit("Endorsement differs: " + "; ".join(endorse))
    if not (relabel or retag):
        print("Data product governance matches Terraform.")


if __name__ == "__main__":
    main(apply="--apply" in sys.argv[1:])
